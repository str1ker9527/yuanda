import { electronExecutable, projectEnvironment } from './platform-runtime.mjs';
import {spawn} from 'node:child_process';
import {access,mkdir,readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),runtime=path.join(root,'.local','drag-preview-ui');
await mkdir(path.join(root,'.local','tmp'),{recursive:true});
const executable=electronExecutable(root),entry=path.join(root,'scripts/drag-preview-regression.mjs');
await Promise.all([access(executable),access(entry),access(path.join(root,'app/preload.cjs'))]);
const env=projectEnvironment(root);delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(executable,[entry,...process.argv.slice(2)],{cwd:root,windowsHide:true,stdio:'inherit',env});
const timer=setTimeout(()=>{child.kill();console.error('拖动预览回归超过 120 秒。');},120000);
child.on('error',error=>{clearTimeout(timer);console.error(error.message);process.exitCode=1;});
child.on('exit',async code=>{clearTimeout(timer);const output=process.argv.find(value=>value.startsWith('--output='))?.slice(9)||'result.json';try{const result=JSON.parse(await readFile(path.join(runtime,output),'utf8'));console.log(JSON.stringify({ok:result.ok,checks:result.checks,errors:result.errors,fatal:result.fatal,evidence:result.evidence,report:path.join(runtime,output)},null,2));}catch{console.error('未生成拖动预览回归结果');}process.exitCode=typeof code==='number'?code:1;});
